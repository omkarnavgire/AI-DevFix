package com.aidevfix.controller;

import com.aidevfix.dto.AnalysisResponse;
import com.aidevfix.dto.CodeAnalysisRequest;
import com.aidevfix.service.NebiusNemotronService;
import jakarta.validation.Valid;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping("/api/v1/analysis")
public class CodeAnalysisController {
    private final NebiusNemotronService service;
    public CodeAnalysisController(NebiusNemotronService service) { this.service = service; }

    @PostMapping
    public AnalysisResponse analyze(@Valid @RequestBody CodeAnalysisRequest request) {
        String result = service.analyze(request);
        return new AnalysisResponse(true, "AI DevFix", "Nebius Token Factory", service.model(), request.language(), result,
                "Analysis generated by the configured model. Review suggested fixes before using them.");
    }
}
